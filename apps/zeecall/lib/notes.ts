export interface NotesSummary {
  roomName: string;
  durationSeconds: number;
  /** Everyone on the call, the local user first. */
  attendees: string[];
  notes: string;
  /** Date part (YYYY-MM-DD) and the full local timestamp of the export. */
  date: string;
  timestamp: string;
}

/** The exported Markdown: a short header (room, duration, attendees), then the notes. */
export function buildNotesMarkdown({ roomName, durationSeconds, attendees, notes, date, timestamp }: NotesSummary): string {
  const minutes = Math.floor(durationSeconds / 60);
  const seconds = durationSeconds % 60;

  return [
    `# zeecall Meeting Summary — ${date}`,
    ``,
    `- **Room**: ${roomName || "Private Call"}`,
    `- **Duration**: ${minutes}m ${seconds}s`,
    `- **Attendees**: ${attendees.join(", ")}`,
    `- **Timestamp**: ${timestamp}`,
    ``,
    `---`,
    ``,
    `## Meeting Notes`,
    ``,
    notes,
    ``,
    `---`,
    `*Generated by [zeecall](https://call.wzee.dev) — Zero-account WebRTC conferencing*`,
  ].join("\n");
}
